<p class="mb-4 text-dark-600 dark:text-dark-300 leading-relaxed">Self-harm or suicidal thoughts can occur in depression, but they can also occur with anxiety, trauma-related problems, severe stress, substance use, other mental-health conditions, or intense emotional distress.</p>
